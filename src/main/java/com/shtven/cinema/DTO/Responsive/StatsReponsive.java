package com.shtven.cinema.DTO.Responsive;

public class StatsReponsive {

    private int AllFunctions;
    private int AllFunctionsActive;
    private int AllMovies;

    public int getAllFunctions() {
        return AllFunctions;
    }

    public void setAllFunctions(int allFunctions) {
        AllFunctions = allFunctions;
    }

    public int getAllFunctionsActive() {
        return AllFunctionsActive;
    }

    public void setAllFunctionsActive(int allFunctionsActive) {
        AllFunctionsActive = allFunctionsActive;
    }

    public int getAllMovies() {
        return AllMovies;
    }

    public void setAllMovies(int allMovies) {
        AllMovies = allMovies;
    }
}
